#!/usr/bin/env python3
"""Generate pre-rotated, anti-aliased aircraft icons for the radar.

The ESP32-C3 has no FPU, so instead of rasterising rotated polygons at run
time the firmware blits these coverage masks (one per 5 degrees of heading).

Each pixel is one byte: high nibble = dark outline coverage, low nibble =
fill coverage (0..15).

    python3 scripts/build_aircraft_icons.py [--preview out.png]

Output: src/data/aircraft_icons_data.cpp
"""

import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw

SIZE = 25          # icon cell (px), odd so the aircraft position is the centre pixel
HEADINGS = 72      # 5 degree steps
SS = 8             # supersampling factor
OUTLINE_PX = 1.5   # dark halo around the silhouette

OUT = Path(__file__).resolve().parent.parent / "src" / "data" / "aircraft_icons_data.cpp"


def mirror(points):
    """Right-hand outline (nose -> tail) mirrored into a closed polygon."""
    return points + [(-x, y) for x, y in reversed(points)]


# Shapes are in "aircraft lengths": nose at y = -0.5, tail at y = +0.5.
JET = [mirror([
    (0.00, -0.50), (0.045, -0.44), (0.065, -0.34), (0.065, -0.13),
    (0.47, 0.13), (0.47, 0.21), (0.065, 0.09), (0.060, 0.30),
    (0.20, 0.43), (0.20, 0.49), (0.035, 0.44), (0.00, 0.50),
])]

LIGHT = [mirror([
    (0.00, -0.50), (0.06, -0.44), (0.075, -0.30), (0.075, -0.22),
    (0.50, -0.19), (0.50, -0.05), (0.075, -0.01), (0.045, 0.34),
    (0.21, 0.36), (0.21, 0.47), (0.03, 0.47), (0.00, 0.50),
])]


def ellipse(cx, cy, rx, ry, n=20):
    return [(cx + rx * math.cos(2 * math.pi * i / n), cy + ry * math.sin(2 * math.pi * i / n))
            for i in range(n)]


def bar(x0, y0, x1, y1, half):
    dx, dy = x1 - x0, y1 - y0
    ln = math.hypot(dx, dy)
    nx, ny = -dy / ln * half, dx / ln * half
    return [(x0 + nx, y0 + ny), (x1 + nx, y1 + ny), (x1 - nx, y1 - ny), (x0 - nx, y0 - ny)]


HELI = [
    ellipse(0.0, -0.12, 0.13, 0.24),                 # cabin
    bar(0.0, 0.05, 0.0, 0.48, 0.035),                # tail boom
    bar(-0.13, 0.45, 0.13, 0.45, 0.035),             # tail rotor / stabiliser
    bar(-0.36, -0.48, 0.36, 0.24, 0.035),            # main rotor blade
    bar(0.36, -0.48, -0.36, 0.24, 0.035),            # main rotor blade
]

# name, polygons, length in px
SHAPES = [
    ("jet", JET, 22.0),
    ("light", LIGHT, 18.0),
    ("heli", HELI, 19.0),
]


def render(polys, length_px, heading_deg):
    big = SIZE * SS
    c = big / 2.0
    rad = math.radians(heading_deg)
    cos_h, sin_h = math.cos(rad), math.sin(rad)
    scale = length_px * SS

    def xf(p):
        x, y = p[0] * scale, p[1] * scale
        # heading 0 = up; clockwise positive (screen y grows downward)
        return (c + x * cos_h - y * sin_h, c + x * sin_h + y * cos_h)

    fill = Image.new("L", (big, big), 0)
    outline = Image.new("L", (big, big), 0)
    df, do = ImageDraw.Draw(fill), ImageDraw.Draw(outline)
    ow = int(round(OUTLINE_PX * 2 * SS))
    for poly in polys:
        pts = [xf(p) for p in poly]
        df.polygon(pts, fill=255)
        do.polygon(pts, fill=255)
        do.line(pts + [pts[0]], fill=255, width=ow, joint="curve")
        r = ow / 2
        for x, y in pts:
            do.ellipse((x - r, y - r, x + r, y + r), fill=255)
    fill = fill.resize((SIZE, SIZE), Image.BOX)
    outline = outline.resize((SIZE, SIZE), Image.BOX)
    return fill, outline


def main():
    preview = None
    if "--preview" in sys.argv:
        preview = sys.argv[sys.argv.index("--preview") + 1]

    lines = [
        "// Generated by scripts/build_aircraft_icons.py - do not edit.",
        '#include "data/aircraft_icons.h"',
        "",
        "namespace data::aircraft_icons {",
        "",
        "const uint8_t kIcons[kShapeCount][kHeadingCount][kIconSize * kIconSize] = {",
    ]
    sheet = Image.new("RGB", (SIZE * 24 * 4, SIZE * 3 * len(SHAPES) * 4), (5, 14, 34))
    for si, (name, polys, length_px) in enumerate(SHAPES):
        lines.append(f"  {{  // {name}")
        for h in range(HEADINGS):
            fill, outline = render(polys, length_px, h * 360.0 / HEADINGS)
            fb, ob = fill.tobytes(), outline.tobytes()
            packed = bytes((((o * 15 + 127) // 255) << 4) | ((f * 15 + 127) // 255)
                           for f, o in zip(fb, ob))
            lines.append("    {" + ",".join(str(b) for b in packed) + "},")
            if preview:
                cell = Image.new("RGB", (SIZE, SIZE), (5, 14, 34))
                cell.paste((2, 6, 16), mask=outline)
                cell.paste((90, 220, 140), mask=fill)
                cell = cell.resize((SIZE * 4, SIZE * 4), Image.NEAREST)
                sheet.paste(cell, ((h % 24) * SIZE * 4, (si * 3 + h // 24) * SIZE * 4))
        lines.append("  },")
    lines += ["};", "", "}  // namespace data::aircraft_icons", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.name}: {len(SHAPES)} shapes x {HEADINGS} headings x {SIZE}x{SIZE}")
    if preview:
        sheet.save(preview)


if __name__ == "__main__":
    main()
